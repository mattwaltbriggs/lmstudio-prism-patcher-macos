#!/usr/bin/env bash
set -euo pipefail

# Installs a macOS launchd user agent that keeps LM Studio patched.
#
# LM Studio's plugin API exposes no startup / runtime-update / model-load hooks,
# so a plugin cannot react to backends being downloaded. Instead we use launchd:
#   - WatchPaths on the backends directory  -> fires the moment LM Studio
#     installs or removes a backend
#   - StartInterval                         -> safety net for in-place rewrites
#   - RunAtLoad                             -> patch at login
#
# The agent calls prism_patcher.sh --check first, which is a purely local,
# no-network test of whether every installed backend already carries a PrismML
# stamp. Only when something is missing does it download and patch.
#
# Usage:
#   ./install-watcher.sh            install (or reinstall) the watcher
#   ./install-watcher.sh status     show agent state
#   ./install-watcher.sh uninstall  remove the agent

LABEL="com.mattwaltbriggs.lmstudio-prism-patcher"
SUPPORT_DIR="$HOME/Library/Application Support/lmstudio-prism-patcher"
PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"
BACKENDS_DIR="${LMSTUDIO_BACKENDS_DIR:-$HOME/.lmstudio/extensions/backends}"
SRC_DIR="$(cd "$(dirname "$0")" && pwd)"
UID_NUM="$(id -u)"

if [ "$(uname -s)" != "Darwin" ]; then
    echo "Error: this watcher is macOS-only."
    exit 1
fi

bootout() {
    launchctl bootout "gui/$UID_NUM/$LABEL" 2>/dev/null || \
        launchctl bootout "gui/$UID_NUM" "$PLIST" 2>/dev/null || \
        launchctl unload -w "$PLIST" 2>/dev/null || true
}

case "${1:-install}" in
    install)
        if [ ! -f "$SRC_DIR/prism_patcher.sh" ]; then
            echo "Error: prism_patcher.sh not found next to this script."
            exit 1
        fi

        echo "Installing to: $SUPPORT_DIR"
        mkdir -p "$SUPPORT_DIR" "$HOME/Library/LaunchAgents"
        cp -f "$SRC_DIR/prism_patcher.sh" "$SUPPORT_DIR/prism_patcher.sh"
        chmod +x "$SUPPORT_DIR/prism_patcher.sh"

        cat > "$SUPPORT_DIR/watch.sh" <<'WATCH_EOF'
#!/bin/bash
# Auto-generated by install-watcher.sh -- edits here are overwritten on reinstall.
set -u
export PATH="/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"

SUPPORT_DIR="$HOME/Library/Application Support/lmstudio-prism-patcher"
PATCHER="$SUPPORT_DIR/prism_patcher.sh"
LOG="$SUPPORT_DIR/watcher.log"
COOLDOWN_SECONDS=60

log() { printf '%s %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*" >> "$LOG"; }

# Keep the log from growing without bound
if [ -f "$LOG" ] && [ "$(stat -f%z "$LOG" 2>/dev/null || echo 0)" -gt 1048576 ]; then
    mv -f "$LOG" "$LOG.1"
fi

# Damp the launchd triggers that our own writes into the backends directory cause
NOW="$(date +%s)"
LAST="$(cat "$SUPPORT_DIR/.last-run" 2>/dev/null || echo 0)"
case "$LAST" in ''|*[!0-9]*) LAST=0 ;; esac
if [ $((NOW - LAST)) -lt "$COOLDOWN_SECONDS" ]; then
    exit 0
fi

# Single instance
if ! mkdir "$SUPPORT_DIR/.lock.d" 2>/dev/null; then
    exit 0
fi
trap 'rmdir "$SUPPORT_DIR/.lock.d" 2>/dev/null' EXIT
printf '%s\n' "$NOW" > "$SUPPORT_DIR/.last-run"

# Local-only check: is every backend already patched?
if "$PATCHER" --check >/dev/null 2>&1; then
    exit 0
fi

log "unpatched backend detected; letting LM Studio settle before patching"
sleep 10

log "running patcher"
if "$PATCHER" >> "$LOG" 2>&1; then
    log "patch ok"
else
    log "patch FAILED (see log above)"
fi
WATCH_EOF
        chmod +x "$SUPPORT_DIR/watch.sh"

        cat > "$PLIST" <<PLIST_EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>$LABEL</string>
    <key>ProgramArguments</key>
    <array>
        <string>/bin/bash</string>
        <string>$SUPPORT_DIR/watch.sh</string>
    </array>
    <key>WatchPaths</key>
    <array>
        <string>$BACKENDS_DIR</string>
    </array>
    <key>RunAtLoad</key>
    <true/>
    <key>StartInterval</key>
    <integer>900</integer>
    <key>ThrottleInterval</key>
    <integer>30</integer>
    <key>ProcessType</key>
    <string>Background</string>
    <key>StandardOutPath</key>
    <string>$SUPPORT_DIR/launchd.log</string>
    <key>StandardErrorPath</key>
    <string>$SUPPORT_DIR/launchd.log</string>
</dict>
</plist>
PLIST_EOF

        bootout
        if ! launchctl bootstrap "gui/$UID_NUM" "$PLIST" 2>/dev/null; then
            launchctl load -w "$PLIST"
        fi
        launchctl kickstart -k "gui/$UID_NUM/$LABEL" 2>/dev/null || true

        echo "Watching: $BACKENDS_DIR"
        echo "Patcher:  $SUPPORT_DIR/prism_patcher.sh"
        echo "Logs:     $SUPPORT_DIR/watcher.log"
        echo
        echo "Installed. LM Studio backends will now be patched automatically"
        echo "whenever you restart or log in, and within 15 minutes of any update."
        ;;

    status)
        echo "Agent: $LABEL"
        launchctl print "gui/$UID_NUM/$LABEL" 2>/dev/null | grep -E 'state|path|program|last exit' || \
            echo "  not loaded"
        echo
        echo "Installed files:"
        ls -la "$SUPPORT_DIR" 2>/dev/null || echo "  (none)"
        echo
        if [ -x "$SUPPORT_DIR/prism_patcher.sh" ] && \
           "$SUPPORT_DIR/prism_patcher.sh" --check >/dev/null 2>&1; then
            echo "Backends: all patched"
        else
            echo "Backends: at least one needs patching (or check failed)"
        fi
        ;;

    uninstall)
        bootout
        rm -f "$PLIST"
        rm -rf "$SUPPORT_DIR"
        echo "Uninstalled. (Backends keep their current patches.)"
        ;;

    *)
        echo "Usage: $0 [install|status|uninstall]"
        exit 2
        ;;
esac
